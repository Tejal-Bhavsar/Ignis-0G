import { useEffect, useState } from 'react';
import {
  Bot,
  Command,
  Database,
  Download,
  Flame,
  Globe,
  Search,
  ShieldAlert,
} from 'lucide-react';
import { api } from './api';
import AskDrawer from './components/AskDrawer';
import CommandPalette from './components/CommandPalette';
import DetectionSuppressionTab from './components/DetectionSuppressionTab';
import RankerTab from './components/RankerTab';
import SimulatorTab from './components/SimulatorTab';
import SpinoffsTab from './components/SpinoffsTab';

const TABS = [
  { id: 'ranker', label: 'PSI Studies & Matrix', icon: Database },
  { id: 'simulator', label: 'Habitat Flammability Modeler', icon: Flame },
  { id: 'detection', label: 'Detection & Suppression', icon: ShieldAlert },
  { id: 'spinoffs', label: 'Earth Spin-Offs', icon: Globe },
];

function NasaMissionEmblem() {
  return (
    <svg viewBox="0 0 40 40" className="h-9 w-9 shrink-0" aria-hidden="true">
      <circle cx="20" cy="20" r="19" fill="#072963" stroke="#3B82F6" strokeOpacity="0.45" strokeWidth="1.2" />
      <circle cx="11" cy="12" r="0.9" fill="#FFFFFF" opacity="0.9" />
      <circle cx="29" cy="11" r="0.8" fill="#FFFFFF" opacity="0.8" />
      <circle cx="30" cy="26" r="0.9" fill="#FFFFFF" opacity="0.85" />
      <path d="M8 26 Q20 13 32 15" fill="none" stroke="#FC3D21" strokeWidth="2.4" strokeLinecap="round" />
      <path d="M14 28 L20 10 L26 28" fill="none" stroke="#FFFFFF" strokeWidth="2.1" strokeLinecap="round" strokeLinejoin="round" />
      <circle cx="20" cy="20" r="2.6" fill="#38BDF8" />
    </svg>
  );
}

export default function App() {
  const [activeTab, setActiveTab] = useState('ranker');
  const [drawerOpen, setDrawerOpen] = useState(false);
  const [cmdOpen, setCmdOpen] = useState(false);
  const [health, setHealth] = useState(null);
  const [studiesList, setStudiesList] = useState([]);
  const [hardwareRacks, setHardwareRacks] = useState([]);
  const [focusedStudyId, setFocusedStudyId] = useState(null);
  const [audienceLens, setAudienceLens] = useState('Engineer');
  const [exporting, setExporting] = useState(false);
  const [queuedPrompt, setQueuedPrompt] = useState(null);

  const [habitatState, setHabitatState] = useState({
    o2_pct: 34.0,
    pressure_psia: 8.2,
    airflow_cms: 10.0,
    gravity_target: '1/6g',
  });

  useEffect(() => {
    api.health().then(setHealth).catch(console.error);
    api.studies().then((res) => setStudiesList(res.studies || [])).catch(console.error);
    api
      .hardware()
      .then((res) => setHardwareRacks(res.hardware_racks || []))
      .catch(console.error);
  }, []);

  useEffect(() => {
    const onKeyDown = (e) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
        e.preventDefault();
        setCmdOpen((v) => !v);
      }
    };
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  }, []);

  const handleInspectStudy = (studyId) => {
    setFocusedStudyId(studyId);
    setActiveTab('ranker');
    setDrawerOpen(false);
  };

  const handleAskSI = (promptText) => {
    setQueuedPrompt({ text: promptText, nonce: Date.now() });
    setDrawerOpen(true);
  };

  const handleExportBrief = async () => {
    if (exporting) return;
    setExporting(true);
    try {
      const sim = await api.simulate(habitatState);
      const md = [
        '# IGNIS-PSI Mission Fire Safety Brief',
        `**Audience Lens:** ${audienceLens}`,
        `**Operating Habitat:** ${sim.operating_point.o2_pct}% O2 | ${sim.operating_point.pressure_psia} psia | ${sim.operating_point.airflow_cms} cm/s | ${sim.operating_point.gravity_label}`,
        `**pO2:** ${sim.operating_point.po2_psia} psia | **Risk Level:** ${sim.metrics.risk_level} | **0g LOC:** ${sim.metrics.loc_0g_pct}% O2 | **Target Gravity LOC:** ${sim.metrics.loc_target_pct}% O2 | **Spread Multiplier:** ${sim.metrics.spread_rate_multiplier}×`,
        '',
        '## Active Safety Advisories',
        ...sim.warnings.map((w) => `- **${w.title}** (${w.severity}): ${w.detail} ${w.citation}`),
        '',
        '## Top Ranked NASA PSI Evidence',
        ...(sim.ranked_evidence || []).map(
          (r) =>
            `- **[${r.study.study_id} | ${r.study.acronym} | ${r.study.doi}]** (Match ${(r.total_score * 100).toFixed(0)}%) — ${r.study.title} (${r.study.o2_range}, ${r.study.pressure_psia}, ${r.study.airflow_cm_s})`
        ),
        '',
        '*Generated by IGNIS-PSI (NASA Space Apps Challenge 2026 — Flame in Freefall). High-velocity rocket/propellant combustion is outside PSI scope.*',
      ].join('\n');

      const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `ignis-psi-brief-${habitatState.gravity_target.replace('/', '-')}-${habitatState.o2_pct}pctO2.md`;
      a.click();
      URL.revokeObjectURL(url);
    } catch (e) {
      console.error(e);
    } finally {
      setExporting(false);
    }
  };

  return (
    <div className="min-h-screen bg-[#EAEFF6] text-slate-900">
      {/* Signature NASA Blue Top Masthead + Clean White Sub-Navigation */}
      <header className="sticky top-0 z-30 shadow-sm">
        <div className="bg-gradient-to-r from-[#072963] via-[#0B3D91] to-[#0D47A1] text-white">
          <div className="mx-auto flex max-w-7xl flex-wrap items-center justify-between gap-3 px-4 py-3 sm:px-6">
            <div className="flex items-center gap-3">
              <NasaMissionEmblem />
              <div>
                <div className="flex items-center gap-2">
                  <h1 className="font-display text-lg font-bold tracking-wide text-white">
                    IGNIS-PSI
                  </h1>
                  <span className="rounded bg-[#FC3D21] px-2 py-0.5 font-mono text-[10px] font-semibold tracking-wider text-white">
                    FLAME IN FREEFALL
                  </span>
                  {health?.counts && (
                    <span className="hidden font-mono text-[11px] text-sky-100/80 md:inline">
                      · {health.counts.total_studies} Studies · {health.counts.total_publications} DOIs
                    </span>
                  )}
                </div>
                <p className="text-xs text-sky-100/80">
                  NASA Microgravity Combustion &amp; Exploration Fire Safety Intelligence
                </p>
              </div>
            </div>

            <div className="flex items-center gap-2.5">
              <button
                onClick={() => setCmdOpen(true)}
                className="hidden items-center gap-2 rounded-md border border-white/20 bg-white/10 px-2.5 py-1.5 text-xs text-sky-100 transition hover:bg-white/20 md:inline-flex"
                title="Quick Jump & Grab (Cmd+K / Ctrl+K)"
              >
                <Search className="h-3.5 w-3.5 text-sky-200" />
                <span>Quick Jump</span>
                <kbd className="inline-flex items-center gap-0.5 rounded bg-white/15 px-1.5 py-0.5 font-mono text-[10px] text-white">
                  <Command className="h-2.5 w-2.5" />K
                </kbd>
              </button>

              <div className="hidden items-center gap-2 rounded-md border border-white/15 bg-white/10 px-3 py-1.5 font-mono text-[11px] text-white backdrop-blur xl:flex">
                <span className="h-2 w-2 rounded-full bg-emerald-400" />
                <span>{habitatState.o2_pct}% O2</span>
                <span className="text-white/30">|</span>
                <span>{habitatState.pressure_psia} psia</span>
                <span className="text-white/30">|</span>
                <span>{habitatState.airflow_cms} cm/s</span>
                <span className="text-white/30">|</span>
                <span className="font-semibold text-sky-200">{habitatState.gravity_target}</span>
              </div>

              <button
                onClick={handleExportBrief}
                disabled={exporting}
                className="inline-flex items-center gap-1.5 rounded-md border border-white/25 bg-white/10 px-3 py-2 text-xs font-medium text-white transition hover:bg-white/20 disabled:opacity-50"
              >
                <Download className="h-3.5 w-3.5" />
                {exporting ? 'Exporting...' : 'Export Brief'}
              </button>

              <button
                onClick={() => setDrawerOpen(true)}
                className="inline-flex items-center gap-1.5 rounded-md bg-[#FC3D21] px-3.5 py-2 text-xs font-semibold text-white shadow-sm transition hover:bg-[#E03116]"
              >
                <Bot className="h-4 w-4" />
                Ask SI Engineer
              </button>
            </div>
          </div>
        </div>

        {/* Crisp White Sub-Navigation Bar */}
        <div className="border-b border-slate-200 bg-white">
          <div className="mx-auto flex max-w-7xl items-center justify-between gap-4 px-4 sm:px-6">
            <nav className="-mb-px flex gap-6 overflow-x-auto">
              {TABS.map((t) => {
                const Icon = t.icon;
                const active = activeTab === t.id;
                return (
                  <button
                    key={t.id}
                    onClick={() => setActiveTab(t.id)}
                    className={`inline-flex shrink-0 items-center gap-2 border-b-2 py-2.5 text-xs font-semibold transition ${
                      active
                        ? 'border-[#0B3D91] text-[#0B3D91]'
                        : 'border-transparent text-slate-500 hover:border-slate-300 hover:text-slate-800'
                    }`}
                  >
                    <Icon className={`h-3.5 w-3.5 ${active ? 'text-[#FC3D21]' : 'text-slate-400'}`} />
                    {t.label}
                  </button>
                );
              })}
            </nav>

            <div className="hidden items-center gap-2 py-1.5 sm:flex">
              <span className="text-[11px] font-medium text-slate-400">Lens:</span>
              <select
                value={audienceLens}
                onChange={(e) => setAudienceLens(e.target.value)}
                aria-label="Audience view"
                className="rounded-md border border-slate-200 bg-slate-50 px-2.5 py-1 text-xs font-medium text-slate-700 focus:border-[#0B3D91] focus:outline-none"
              >
                <option value="Engineer">Aerospace Engineer</option>
                <option value="Researcher">Combustion Researcher</option>
                <option value="Student">Student / Educator</option>
              </select>
            </div>
          </div>
        </div>
      </header>

      {/* Main Content */}
      <main className="mx-auto max-w-7xl px-4 py-6 sm:px-6">
        {activeTab === 'ranker' && (
          <RankerTab
            habitatState={habitatState}
            hardwareRacks={hardwareRacks}
            focusedStudyId={focusedStudyId}
            audienceLens={audienceLens}
            onOpenSimulator={() => setActiveTab('simulator')}
            onAskSI={handleAskSI}
          />
        )}
        {activeTab === 'simulator' && (
          <SimulatorTab
            habitatState={habitatState}
            setHabitatState={setHabitatState}
            onInspectStudy={handleInspectStudy}
            onAskSI={handleAskSI}
          />
        )}
        {activeTab === 'detection' && (
          <DetectionSuppressionTab onInspectStudy={handleInspectStudy} onAskSI={handleAskSI} />
        )}
        {activeTab === 'spinoffs' && (
          <SpinoffsTab onInspectStudy={handleInspectStudy} onAskSI={handleAskSI} />
        )}
      </main>

      <AskDrawer
        isOpen={drawerOpen}
        onClose={() => setDrawerOpen(false)}
        habitatState={habitatState}
        onSelectStudy={handleInspectStudy}
        queuedPrompt={queuedPrompt}
      />

      <CommandPalette
        isOpen={cmdOpen}
        onClose={() => setCmdOpen(false)}
        studies={studiesList}
        onSelectStudy={handleInspectStudy}
        onSelectTab={setActiveTab}
        onApplyHabitat={setHabitatState}
        onOpenAsk={() => setDrawerOpen(true)}
      />
    </div>
  );
}
